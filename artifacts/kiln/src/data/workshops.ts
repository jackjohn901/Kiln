export function getWorkshopsByArtist(artistId: string): Workshop[] {
  return workshops.filter((w) => w.artistId === artistId);
}

export function getWorkshopsByMedium(medium: string): Workshop[] {
  if (!medium || medium === "All") return workshops;
  return workshops.filter((w) => w.medium === medium);
}


export function formatDuration(secs: number): string {
  const m = Math.floor(secs / 60);
  const s = secs % 60;
  return `${m}:${s.toString().padStart(2, "0")}`;
}

export function getTrackById(id: string): MusicTrack | undefined {
  return musicTracks.find((t) => t.id === id);
}
